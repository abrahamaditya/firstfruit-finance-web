export function translate(lang: Lang, key: string, vars?: Record<string, string | number>): string {
  const entry = D[key];
  let text = entry ? (lang === 'EN' ? entry.en : entry.id) : key;
  if (vars) for (const name in vars) text = text.replace(new RegExp(`\\{${name}\\}`, 'g'), String(vars[name]));
  return text;
}
